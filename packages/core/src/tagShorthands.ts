/**
 * `styled` with a shorthand for every tag: `styled.div(...styles)` is `styled('div')(...styles)`. Each tag
 * of `TAG_NAMES` is an own enumerable member, so `Object.assign(wrapper, styled)` copies them; it is a
 * getter, so nothing is made until a member is read, and each read makes it as `styled(tag)` does. Another
 * member that the function does not have and that looks like a tag name is made when it is read too. `then`
 * is not a tag, so that `styled` is never taken for a promise.
 */
export function withTagShorthands<F extends object>(styled: F): F {
  const make = styled as (tag: string) => unknown
  for (const tag of TAG_NAMES) {
    Object.defineProperty(styled, tag, {
      get: () => make(tag),
      enumerable: true,
      configurable: true,
    })
  }
  return new Proxy(styled, {
    get(target, key, receiver) {
      if (typeof key !== 'string' || key in target || key === 'then' || !TAG_PATTERN.test(key)) {
        return Reflect.get(target, key, receiver) as unknown
      }
      return make(key)
    },
  })
}
